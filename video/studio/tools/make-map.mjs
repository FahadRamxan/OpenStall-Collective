// Builds src/map-dots.js: a dotted world map (land only) for the hook scene.
// Land shapes come from world-atlas (Natural Earth 1:110m, public domain).
// Run once: node tools/make-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/land-110m.json", import.meta.url)));
const land = feature(topo, topo.objects.land);

// Every polygon as a list of rings (first ring is the outline, the rest are holes).
const polygons = [];
for (const f of land.features) {
  const g = f.geometry;
  if (g.type === "Polygon") polygons.push(g.coordinates);
  else if (g.type === "MultiPolygon") polygons.push(...g.coordinates);
}

function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function onLand(lon, lat) {
  for (const rings of polygons) {
    if (!inRing(lon, lat, rings[0])) continue;
    let hole = false;
    for (let k = 1; k < rings.length; k++) if (inRing(lon, lat, rings[k])) hole = true;
    if (!hole) return true;
  }
  return false;
}

const view = { lon0: -132, lon1: 104, lat0: -6, lat1: 68, step: 1.55 };
const dots = [];
let row = 0;
for (let lat = view.lat1; lat >= view.lat0; lat -= view.step * 0.87, row++) {
  const shift = row % 2 ? view.step / 2 : 0;
  for (let lon = view.lon0 + shift; lon <= view.lon1; lon += view.step) {
    if (onLand(lon, lat)) dots.push([Math.round(lon * 100) / 100, Math.round(lat * 100) / 100]);
  }
}

const out =
  "// Generated by tools/make-map.mjs from world-atlas land-110m (Natural Earth, public domain). Do not edit.\n" +
  "window.MAP_DOTS = " +
  JSON.stringify({ ...view, dots }) +
  ";\n";
writeFileSync(new URL("../src/map-dots.js", import.meta.url), out);
console.log(`map-dots.js: ${dots.length} dots`);
